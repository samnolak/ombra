namespace Ombra.Server;

/// <summary>Server configuration (section "Ombra"; env <c>Ombra__*</c>, written by install.sh to /etc/ombra/server.env).</summary>
public sealed class OmbraOptions
{
    public const string Section = "Ombra";

    public string ConnectionString { get; set; } = "";
    /// <summary>Persistent data: blobs/, transfers/, blob-deletions.log, revocations.log.</summary>
    public string DataDir { get; set; } = "/var/lib/ombra";
    /// <summary>32+ random bytes; tokens are stored as HMAC(key, token). Regenerated on restore.</summary>
    public string TokenKeyFile { get; set; } = "/etc/ombra/token.key";
    /// <summary>serverId generated by install.sh (§2.2, DeviceCertificate).</summary>
    public string ServerIdFile { get; set; } = "/etc/ombra/server-id";

    /// <summary>"ip" — Kestrel terminates TLS 1.3 with the pinned SPKI key; "domain" — plain HTTP behind Caddy.</summary>
    public string Mode { get; set; } = "ip";
    public string? TlsCertFile { get; set; }
    public string? TlsKeyFile { get; set; }
    public string ListenUrl { get; set; } = "https://0.0.0.0:443";

    /// <summary>Off-host copies (file path on a mounted remote FS / object-lock bucket mount). Optional.</summary>
    public string? RevocationsSink { get; set; }
    public string? BlobDeletionsSink { get; set; }

    /// <summary>age binary used by backup/restore (operator key encryption, §1 SD-08).</summary>
    public string AgePath { get; set; } = "age";

    public LimitsOptions Limits { get; set; } = new();

    public string RevocationsLogPath => Path.Combine(DataDir, "revocations.log");
    public string BlobDeletionsLogPath => Path.Combine(DataDir, "blob-deletions.log");
    public string BlobDir => Path.Combine(DataDir, "blobs");
    public string TransferDir => Path.Combine(DataDir, "transfers");
}

/// <summary>Defaults from SERVER_DESIGN §3.0, §3.3, §6.1, §8 п.1.</summary>
public sealed class LimitsOptions
{
    public int OpMaxBytes { get; set; } = 64 * 1024;
    public double DeviceOpsPerSecond { get; set; } = 20;
    public int DeviceOpsBurst { get; set; } = 100;
    public long TeamQueueBytes { get; set; } = 1L << 30;
    public long MemberQueueMinBytes { get; set; } = 100L << 20;
    public int QueueTtlDays { get; set; } = 30;

    public long TransferMaxBytes { get; set; } = 1L << 30;
    public int TransferChunkPlainBytes { get; set; } = 1 << 20;
    /// <summary>AES-GCM tag + framing allowance per chunk.</summary>
    public int ChunkOverheadBytes { get; set; } = 64;
    public int TransferTtlHours { get; set; } = 24;
    public int TransfersPerHour { get; set; } = 5;

    public long BlobMaxBytes { get; set; } = 100L << 20;
    public long TeamBlobQuotaBytes { get; set; } = 10L << 30;
    public int BlobIdleTtlDays { get; set; } = 180;

    public int AccessTokenMinutes { get; set; } = 15;
    public int RefreshTokenDays { get; set; } = 30;
    public int ChallengeSeconds { get; set; } = 120;
    public int ClockSkewSeconds { get; set; } = 300;
    public int EnvelopeResultHours { get; set; } = 24;
    public int AuditRetentionDays { get; set; } = 365;
    public int SyncMaxOps { get; set; } = 500;
    public int SyncMaxBytes { get; set; } = 4 << 20;
    public int RetentionIntervalSeconds { get; set; } = 300;

    // ---- pre-auth DoS limits and request bodies (implementation review) ----
    /// <summary>Per client address, per minute: /session/*, /bootstrap, /invites/*, /stream handshakes.</summary>
    public int PreAuthRequestsPerMinute { get; set; } = 60;
    /// <summary>WebSocket handshakes accepted but still waiting for their auth frame.</summary>
    public int PreAuthStreamsMax { get; set; } = 256;
    /// <summary>Outstanding (unexpired) hello challenges per deviceId and in total.</summary>
    public int ChallengesPerDevice { get; set; } = 5;
    public int ChallengesMax { get; set; } = 100_000;
    /// <summary>Body limit of the unauthenticated JSON endpoints (/session/*, /bootstrap).</summary>
    public int PreAuthBodyBytes { get; set; } = 16 << 10;
    /// <summary>Default body limit (envelopes are ≤ 96 KiB); Kestrel's global limit.</summary>
    public int RequestBodyBytes { get; set; } = 128 << 10;
    /// <summary>Handshake uploads: commit + Welcome JSON (base64), KeyPackage batches, roster/genesis/GroupInfo.</summary>
    public int HandshakeBodyBytes { get; set; } = 4 << 20;

    // ---- WSS ----
    /// <summary>Period of the access re-check of open sockets (0 = only on connect and listener reconnect).</summary>
    public int StreamRevalidateSeconds { get; set; } = 30;
    /// <summary>Presence changes per connection: a bucket of <c>PresenceBurst</c>, one back every <c>PresenceRefillSeconds</c>.</summary>
    public int PresenceBurst { get; set; } = 5;
    public double PresenceRefillSeconds { get; set; } = 2;
}
